#!/usr/bin/env python3
"""
Write the profile-art section of README.md from profile.json.

Only the text between the START/END markers is ever rewritten, so everything
you write by hand around it (about me, projects...) is left alone. A README
without markers gets the section added at the top. The portrait panel appears
once ascii.svg exists; the links row only when profile.json lists links.
"""
import os
import re
from urllib.parse import quote

from common import PROFILE, ROOT

START = "<!-- profile-art:start (generated by scripts/build_readme.py from profile.json; edits here are overwritten) -->"
END = "<!-- profile-art:end -->"
PATH = os.path.join(ROOT, "README.md")

p = PROFILE
cmd = lambda c: f'<h3><code>{p["prompt"]} ~ $ {c}</code></h3>'


def badge(link):
    esc = lambda s: quote(s.replace("-", "--").replace("_", "__"))
    return (f'[![{link["label"]}](https://img.shields.io/badge/{esc(link["label"])}-{esc(link["text"])}-{link["color"]}'
            f'?style=for-the-badge&logo={link.get("logo", "")}&logoColor=white)]({link["url"]})')


stats = f'<img src="./stats.svg" width="420" alt="{p["name"]}\'s GitHub streak and contribution stats" />'
if os.path.exists(os.path.join(ROOT, "ascii.svg")):
    panel = ("<table>\n<tr>\n"
             f'<td valign="top"><img src="./ascii.svg" width="420" alt="{p["name"]} — ASCII portrait" /></td>\n'
             f'<td valign="top">{stats}</td>\n'
             "</tr>\n</table>")
else:
    panel = stats

links = ""
if p.get("links"):
    links = f"""
<br>
<br>

{cmd("./links.sh")}

<p><b>{p["tagline"]}</b></p>

{chr(10).join(badge(l) for l in p["links"])}
"""

section = f"""{START}
<div align="center">

{cmd("./contributions.sh")}

<img src="./contrib-heatmap.svg" width="860" alt="{p["name"]}'s GitHub contribution graph — refreshed daily" />

<br>
<br>

{cmd("whoami")}

{panel}
{links}
</div>
{END}"""

old = open(PATH, encoding="utf-8").read() if os.path.exists(PATH) else ""
pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.S)
if pattern.search(old):
    new = pattern.sub(lambda _: section, old)
else:
    new = section + ("\n\n" + old if old else "\n")
with open(PATH, "w", encoding="utf-8") as f:
    f.write(new)
print("wrote README.md")
